package ru.titeha.shiftalarm.alarm

/**
 * Флаги функциональности. Изолируют фичи, которые позже могут уйти под платный пакет — тогда достаточно
 * поменять одну константу.
 */
object FeatureFlags {
    /** Жёсткий режим выключения звонка (пример/шаги/встряхивание). Позже — под платный пакет. */
    const val HARD_MODE = true

    /**
     * Показ «Настроения дня» (карточка после «Стоп», уведомление, раздел настроек).
     * Отключено для релиза «только исправления»: публикация не должна приносить новых
     * видимых изменений. Модуль, данные в assets, сохранённые настройки и тесты остаются
     * на месте; включение — смена одной константы.
     */
    const val DAY_GREETING = false
}
